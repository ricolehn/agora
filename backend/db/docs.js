#!/usr/bin/env node
// Writes docs/DATABASE.md - the map of the database - from the definitions in schema/ (the same help texts PocketBase
// shows next to each field on its admin page):   node backend/db/docs.js
// tests/database.test.js fails when the file is out of date, so the map never drifts from the code.
const fs = require('fs');
const path = require('path');
const schema = require('./schema');
const { DAY_PATTERN, MONTH_PATTERN, TIME_PATTERN } = require('./schema/fields');

const OUTPUT = path.join(__dirname, '..', '..', 'docs', 'DATABASE.md');

const typeOf = (field) => {
  if (field.type === 'relation') return `link → ${field.target}${field.maxSelect > 1 ? ' (several)' : ''}${field.cascadeDelete ? ', deleted with it' : ''}`;
  if (field.type === 'text' && field.pattern === DAY_PATTERN) return 'day (YYYY-MM-DD)';
  if (field.type === 'text' && field.pattern === MONTH_PATTERN) return 'month (YYYY-MM)';
  if (field.type === 'text' && field.pattern === TIME_PATTERN) return 'time of day (HH:mm)';
  if (field.type === 'number' && /Cents$/.test(field.name)) return 'money (whole cents)';
  if (field.type === 'number') return field.onlyInt ? 'whole number' : 'number';
  if (field.type === 'select') return `one of: ${field.values.join(', ')}${field.maxSelect > 1 ? ' (several)' : ''}`;
  if (field.type === 'date') return 'moment (date and time, UTC)';
  if (field.type === 'autodate') return 'moment (set by the database)';
  return field.type;
};

const cell = (text) => String(text || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function collectionSection(spec) {
  const lines = [`### ${spec.name}`, '', spec.description || '', ''];
  lines.push('| Field | Kind | Meaning |', '| --- | --- | --- |');
  lines.push(`| id | ${spec.id ? 'text (kept from before the upgrade, or made by PocketBase)' : 'text (made by PocketBase)'} | ${cell(spec.id?.help || 'The record\'s id.')} |`);
  for (const field of spec.fields) {
    const flags = [field.required ? 'required' : '', field.presentable ? 'shown as its name' : ''].filter(Boolean).join(', ');
    lines.push(`| ${field.name} | ${cell(typeOf(field))}${flags ? ` (${flags})` : ''} | ${cell(field.help)} |`);
  }
  if ((spec.indexes || []).length) {
    lines.push('', 'Indexes: ' + spec.indexes.map((sql) => `\`${sql.replace(/^CREATE (UNIQUE )?INDEX \w+ ON \w+ /, (match, unique) => (unique ? 'unique ' : ''))}\``).join(', '));
  }
  lines.push('');
  return lines.join('\n');
}

function viewSection(view) {
  return [`### ${view.name} (view)`, '', view.description || '', '', '```sql', view.viewQuery, '```', ''].join('\n');
}

/** The whole map as Markdown. */
function databaseMap() {
  const collections = schema.allCollections();
  const views = schema.allViews();
  const out = [
    '# The database',
    '',
    '<!-- Generated by backend/db/docs.js from backend/db/schema/ - do not edit by hand. -->',
    '',
    `Agora keeps its data in PocketBase (SQLite). This is structure version ${schema.SCHEMA_VERSION}: every table, every field with its meaning, and the`,
    'links between them. The same texts appear next to each field on PocketBase\'s admin page (port 8090).',
    '',
    '## Rules of the house',
    '',
    '- A table is named `<area>_<things>` (`finance_payments`, `event_duties`); `users` (PocketBase\'s login table) and `events` are the',
    '  main tables of their areas.',
    '- Fields are camelCase. A link is named after what it points to (`member`, `event`, `user`) and is a real link: the admin page',
    '  opens the linked record.',
    '- Money is always a whole number of cents in a field ending in `Cents` (`amountCents: 5000` is 50.00) - no rounding errors.',
    '- A calendar day is text `YYYY-MM-DD`, a month `YYYY-MM`, a moment in time a date field (UTC).',
    '- Fixed choices are select fields; every table has `created` and `updated`.',
    '- `original` (in many tables): exactly how an older app wrote a record where the columns cannot show it (an amount typed as',
    '  "50,00", a link to something deleted since). Only the old API reads it; it is empty for almost every record. Do not edit it.',
    '- Every table is the server\'s alone: no app and no member token reads it directly; the server checks every permission.',
    '- Do not change records on the admin page while the app runs unless you know what the server expects: it does not check them.',
    '',
    '## Areas',
    ''
  ];
  for (const area of schema.AREAS) {
    const names = collections.filter((spec) => spec.area === area.key).map((spec) => `\`${spec.name}\``);
    const areaViews = views.filter((view) => view.area === area.key).map((view) => `\`${view.name}\` (view)`);
    out.push(`- **${area.title}**: ${[...names, ...areaViews].join(', ')}`);
  }
  out.push('- **Accounts**: `users` (PocketBase\'s login table; fields below)', '');
  out.push('## users', '', 'The login accounts (PocketBase\'s own table: e-mail address, password and verification are PocketBase\'s fields).', '');
  out.push('| Field | Kind | Meaning |', '| --- | --- | --- |');
  for (const field of schema.USERS_FIELDS) out.push(`| ${field.name} | ${cell(typeOf(field))} | ${cell(field.help)} |`);
  out.push('');
  for (const area of schema.AREAS) {
    const specs = collections.filter((spec) => spec.area === area.key);
    const areaViews = views.filter((view) => view.area === area.key);
    if (!specs.length && !areaViews.length) continue;
    out.push(`## ${area.title}`, '');
    for (const spec of specs) out.push(collectionSection(spec));
    for (const view of areaViews) out.push(viewSection(view));
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, databaseMap());
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
}

module.exports = { databaseMap, OUTPUT };
